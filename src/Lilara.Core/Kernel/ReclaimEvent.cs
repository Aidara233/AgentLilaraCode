namespace Lilara.Core.Kernel;

/// <summary>
/// **一次回收窗口**——「从这一刻起，下面这批结果换成注记」。
///
/// <para>⚠️ <b>为什么它必须是记录，而不是渲染时现算的东西</b>（2026-10-17 更正）：
/// 回收改的是前缀**中段** ⇒ 它只许在**失效窗口**（前缀反正要重建）里动手
/// （[`00` §3](../docs/00-设计哲学.md)：热路径「绝不事后清理」）。
/// 渲染发生在**每一步**，而「这一步是不是窗口」不是渲染自己知道的输入——
/// 它是一次**事件**的结果（用户喊了 `session.gc` / 压缩落了一个检查点 / 模型画了 `release` 线）。
/// ⇒ 那件事必须落成一条记录；渲染只读它，绝不自己决定。</para>
///
/// <para>⚠️ <b>它为什么不进模型上下文</b>：与 <see cref="ReleaseEvent"/> 同一条理由——
/// 它是给我们自己的锚，不是对话。渲染层把它过滤掉（`TimelineRender.IsRenderable`）；
/// 而**判定**读它（`Reclaim.Decide`）。</para>
///
/// <para>⚠️ <b>为什么存<b>已解析的 id</b>，而不是存「当时的规则 + 参数」</b>：
/// 距离（最近 N 条）与点杀（重读源文件）都是**解析那一刻**的世界。
/// 把规则落盘、每次渲染重解，会让同一条结果在不同步得到不同结论 ⇒ **每步破前缀**，
/// 正是这一批要修的形状。解析一次、冻住结果，与 `SystemBlock` 的「步内一冻」同一条纪律。</para>
///
/// <para>⚠️ <b>它不动盘上的记录</b>：与回收本身一样，它是「渲染的一份输入」。
/// 删掉这一条（或它的 id 不再指向存在的记录），对应的结果就回到原文——那是合法的回滚，
/// 而且这正是「只追加」的账本形状带来的：**回滚 = 追一条修正，不 = 改写历史**。</para>
/// </summary>
public sealed record ReclaimEvent : TimelineEvent
{
    /// <summary>
    /// 是什么开了这个窗口。**它不是判据**（渲染只读 <see cref="Ids"/>），
    /// 而是给人看、给排查用的一句话；同时让「这条窗口从哪来」不必去猜时间相邻。
    /// </summary>
    public required string Trigger { get; init; }

    /// <summary>
    /// 这一次窗口换掉的结果——**记录 id**（不是协议 `CallId`，同 `fetch` 的取回地址）。
    /// 空列表是合法的：窗口开了而一条都没收（例如全在保护带里）——它照样要落，
    /// 因为「这一刻判过」本身是事实，且它让 `session.gc` 的回执与事件说的同一件事。
    /// </summary>
    public required IReadOnlyList<string> Ids { get; init; }

    /// <summary>给**人**看的一句：为什么收了（或为什么没收）。不回放进模型。</summary>
    public string? Note { get; init; }
}
