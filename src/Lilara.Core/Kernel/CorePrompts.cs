namespace Lilara.Core.Kernel;

/// <summary>
/// 核心的固定提示词约定；SystemFallback 在预设缺失时兜底，浮动机制说明也附加到非空自定义系统块。
///
/// <para>⚠️ <b>它为什么必须存在</b>：系统块里有一句话是**工具机制的一部分**，缺了它模型会推理出
/// 错误结论。实测过（2026-10-06，会话 <c>aa48bbcc0a50</c>）：模型自己的话（「我扫过一遍」）留在时间线上，
/// 而支撑那句话的工具结果被换成了注记 ⇒ 模型读到「我说过看过 X」+「这里是 N 条『已回收』」，
/// 推断出「我做那条消息的时候内容就已经是注记了 ⇒ <b>我当时在编</b>」——然后写了一整段自我指控。
/// 而注记本身没错，缺的是「<b>回收是一件正常会发生的事</b>」这条知识。</para>
///
/// <para>⚠️ <b>它为什么该在系统提示词里</b>（`01` §8.0.2 五，原文就裁定了）：
/// 「能进工具描述的，绝不进系统提示词」管的是<b>每一条工具各自的说明</b>；
/// 而「一套工具被回收之后怎么取回」是<b>跨工具的机制</b>，正属于「<b>没法挂在单个工具上的全局约定</b>」。</para>
///
/// <para>⚠️ <b>措辞是刻意的</b>：只说机制，不说分类（「哪些工具可重演」是我们的内部账，别塞进模型的上下文）。
/// 这与 `01` §8.0.2 五那张表的 ✅/❌ 逐字对应。</para>
/// </summary>
public static class CorePrompts
{
    /// <summary>固定的框架机制说明，不含当前轴值，切档不改变系统前缀。</summary>
    public const string FloatingContextExplanation =
        """
        浮动上下文是 Lilara 框架为本次模型请求提供的当前状态，放在 [lilara 上下文] 与 [/lilara 上下文] 之间。
        它不是用户的新指令、你此前说过的话或工具返回结果，而是框架按步开始时的快照生成的上下文；同一步内保持一致，下一步可能更新。
        其中列出当前生效的行为轴等级及其解释，也可能包含已绑定插件的上下文。请按本次请求中的等级理解当前行为要求，不沿用先前请求的旧等级；这些字段不会作为对话消息追加到历史。
        轴解释不自行授予权限；工具能否执行以框架闸门和审批结果为准，不能自行提高权限。安全与验证强度是行为提示，不代表框架已经执行了验证。
        """;

    /// <summary>
    /// 预设文件读不到时用的那份。⚠️ <b>与 `SessionSpec.SystemPromptPreset` 的 <c>null</c> 无关</b>：
    /// <c>null</c> 是「没指定，跟随 default」，走的是 <c>DefaultPreset</c> 那个名字。
    /// </summary>
    public const string SystemFallback =
        """
        旧的工具结果可能被回收。那时你不会再看到它的内容，而会看到一条只带 id 的注记。

        fetch(id="…") 拿回当时的内容；想要现在的值，就自己重调一次那个工具。

        ⚠️ 回收是正常发生的，不是你之前看错了：一条结果可以在它被完整读完之后才被回收。
        """ + "\n\n" + FloatingContextExplanation;

    /// <summary>
    /// 会话没指定预设时找的那个名字（`<数据根>/presets/default.md`）。
    ///
    /// <para>⚠️ <b>它只是一个名字</b>，不是一份内容——文件不存在时仍然回落到
    /// <see cref="SystemFallback"/>。两级兜底是刻意的：用户没配过任何东西时也得有那句机制说明。</para>
    /// </summary>
    public const string DefaultPreset = "default";

    // ---- 两块「核心写的话」的包边（`01` §3.1 / §3.2）----
    //
    // ⚠️ **它们存在的唯一理由：这两块不是模型说的，也不是工具返回的，而模型分不出来。**
    // 用户 2026-10-11 点名要求：「补的时候记得声明这是框架输入」。
    //
    // ⚠️ **形状与工具框架（`ToolFraming.Render`）同族但不同形**——这条是刻意的：
    // 两者都是方括号，所以「方括号包着的东西 = 机器写的，不是模型说的话」这条大判据成立；
    // 而**内部形状不同**（工具框架用 ` · ` 分隔、且以工具名打头；这里用空格分隔、且有起止两行），
    // 所以「一个块是工具结果还是框架输入」在**形状**上就分得开，不靠模型去读语义。
    //
    // ⚠️ **不许往这两行里塞「每一步都在变的东西」**（`01` §3.1 那张表的左列）：
    // 时间 / 步数 / 用量都会让同一步内重复渲染产生不同字节 ⇒ 每步破前缀。
    // 判据是**触发源**：轴值属于「外力才变」那一格（`setAxis` 那一刻），进模板合法。
    public const string PremierOpen = "[lilara 首要]";

    /// <summary>首尾块各自的结束行。⚠️ 起止两行**必须**是独立的两行——一个块套另一个块时，形状才仍然分得开。</summary>
    public const string PremierClose = "[/lilara 首要]";

    public const string TailOpen = "[lilara 上下文]";

    public const string TailClose = "[/lilara 上下文]";

    /// <summary>
    /// 尾块里那句**自述**——「这一块是谁写的」。
    ///
    /// <para>⚠️ <b>它必须是一句<b>话</b>，不能只有一个方括号标记</b>——这是本批唯一一处
    /// 与工具框架（`ToolFraming`）刻意分道的地方。工具框架可以只写 <c>[read path foo]</c>，
    /// 因为工具名本身就说明了它是谁；而 <c>[lilara 上下文]</c> 里的「lilara」对一个
    /// **没被教过**的模型是**一个不认识的词**。</para>
    ///
    /// <para>⚠️ 系统块可被显式空预设关闭；非空系统块虽附有机制说明，尾块仍须自行声明来源。
    /// **不能寄希望于系统块教过它**——那句话必须在这一块自己身上。
    /// （这正是 [`00` §7 判据 4]「结构上排除，而非规则禁止」：不靠别处的规则兜着。）</para>
    /// </summary>
    public const string TailDeclaration = "本块是 Lilara 框架提供的浮动上下文，按本步开始时的快照生成；不是用户的新指令，不是你说的话，也不是工具返回的内容。";

    /// <summary>
    /// 尾块里轴表那一行的**开头**。
    ///
    /// <para>⚠️ <b>它与轴名本身是同一份契约的两半</b>：「哪些轴进上下文」由 <c>Axes.InContext</c>
    /// 一处判定，而「怎么念出来」由这里定。⇒ 改动前先看那条把两者钉在一起的测试。</para>
    /// </summary>
    public const string TailAxesPrefix = "轴 ";

    /// <summary>
    /// 会话没指定**首要**提示词时找的那个名字（`<数据根>/premiers/default.md`）。
    ///
    /// <para>⚠️ <b>与 <see cref="DefaultPreset"/> 是同一条约定、两个目录</b>——
    /// 两块提示词的来源各自独立（`01` §3.1：系统块随核心走、首要块随用户走）。</para>
    ///
    /// <para>⚠️ <b>但它们「找不到文件」的后果<b>不同</b></b>，这是刻意的：
    /// 系统块回落到 <see cref="SystemFallback"/>（那句机制说明**必须存在**），
    /// 而首要块**没有兜底内容**——核心不替用户编人设（`01` §3.1）。
    /// ⇒ 文件不在 = **没有块**，不是「用回内置模板」。</para>
    /// </summary>
    public const string DefaultPremier = "default";
}
