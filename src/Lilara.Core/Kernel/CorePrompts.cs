namespace Lilara.Core.Kernel;

/// <summary>
/// **核心自带的那份系统提示词**——只在**一个**场合用：预设文件读不到的时候兜底。
///
/// <para>⚠️ <b>它为什么必须存在</b>：系统块里有一句话是**工具机制的一部分**，缺了它模型会推理出
/// 错误结论。实测过（2026-10-06，会话 <c>aa48bbcc0a50</c>）：模型自己的话（「我扫过一遍」）留在时间线上，
/// 而支撑那句话的工具结果被换成了注记 ⇒ 模型读到「我说过看过 X」+「这里是 N 条『已回收』」，
/// 推断出「我做那条消息的时候内容就已经是注记了 ⇒ <b>我当时在编</b>」——然后写了一整段自我指控。
/// 而注记本身没错，缺的是「<b>回收是一件正常会发生的事</b>」这条知识。</para>
///
/// <para>⚠️ <b>它为什么该在系统提示词里</b>（`01` §8.0.2 五，原文就裁定了）：
/// 「能进工具描述的，绝不进系统提示词」管的是<b>每一条工具各自的说明</b>；
/// 而「一套工具被回收之后怎么取回」是<b>跨工具的机制</b>，正属于「<b>没法挂在单个工具上的全局约定</b>」。</para>
///
/// <para>⚠️ <b>措辞是刻意的</b>：只说机制，不说分类（「哪些工具可重演」是我们的内部账，别塞进模型的上下文）。
/// 这与 `01` §8.0.2 五那张表的 ✅/❌ 逐字对应。</para>
/// </summary>
public static class CorePrompts
{
    /// <summary>
    /// 预设文件读不到时用的那份。⚠️ <b>与 `SessionSpec.SystemPromptPreset` 的 <c>null</c> 无关</b>：
    /// <c>null</c> 是「没指定，跟随 default」，走的是 <c>DefaultPreset</c> 那个名字。
    /// </summary>
    public const string SystemFallback =
        """
        旧的工具结果可能被回收。那时你不会再看到它的内容，而会看到一条只带 id 的注记。

        fetch(id="…") 拿回当时的内容；想要现在的值，就自己重调一次那个工具。

        ⚠️ 回收是正常发生的，不是你之前看错了：一条结果可以在它被完整读完之后才被回收。
        """;

    /// <summary>
    /// 会话没指定预设时找的那个名字（`<数据根>/presets/default.md`）。
    ///
    /// <para>⚠️ <b>它只是一个名字</b>，不是一份内容——文件不存在时仍然回落到
    /// <see cref="SystemFallback"/>。两级兜底是刻意的：用户没配过任何东西时也得有那句机制说明。</para>
    /// </summary>
    public const string DefaultPreset = "default";
}
