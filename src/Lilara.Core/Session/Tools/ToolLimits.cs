namespace Lilara.Core.Session.Tools;

/// <summary>
/// **工具结果的容量上限**（`01` §9.3）。
///
/// <para>⚠️ <b>这里必须是那个数的<b>唯一</b>住址</b>（本计划的 G17）：
/// <see cref="ListTool"/> 里那句「这个文件太大」与 <see cref="ListTool"/> / <c>ReadTool</c>
/// 实际读多少，**都从这里读**。各写一份的后果是——
/// 改一处、另一处**开始说谎**，而**没有任何东西会红**。
/// 同族：`01` §8.0.2「两层判据必须共用一个谓词」（本仓栽过四次的那个形状）。</para>
///
/// <para>⚠️ <b>两个数都是<b>占位值</b></b>，与 <c>Reclaim.ProtectedRecentResults = 4</c>
/// 同一条纪律：`01` §9.3 只裁定了「**必须有所限制**」，**没有**说多少。
/// 取一个保守值并如实标注它是占位——**别把这里的数当成设计结论**。</para>
///
/// <para>⚠️ <b>它们防的是「上下文被撑爆」，不是「内存」</b>（`01` §9.3 用户原话：
/// 「大文件一个 read 下去直接给自己上下文撑爆了」）。所以判据是
/// 「一次结果**进上下文**多少字节」，与盘上文件多大是两件事。</para>
/// </summary>
internal static class ToolLimits
{
    /// <summary>
    /// 一次工具结果**最多**贡献多少字节——**投递**给模型的预算（`01` §9.3）。
    ///
    /// <para>⚠️ <b>它是「投递」不是「保存」</b>（2026-10-17）：工具把**全量**结果交给核心，
    /// 核心原样存进库；这一条预算在**渲染期**才生效——超出部分换成一条带稳定 id 的注记，
    /// 模型仍可以用 `fetch(id, offset)` 取回原文，**不必重跑那个工具**。
    /// ⚠️ 与 <see cref="MaxToolOutputBytes"/>（保存侧上限）是**两个数**：那个防炸盘，这个防上下文。</para>
    ///
    /// <para>⚠️ **占位值**。取 256 KiB 的理由：它远小于任何模型的上下文窗口（撑不爆），
    /// 又大于绝大多数源文件（普通 `read` 不受影响）。
    /// ⚠️ 它**不是**按 token 折算的——本仓没有 token 计数（`01` §11.3 那条同样欠着）。</para>
    ///
    /// <para>⚠️ <b>与 <c>BlobStore.InlineThresholdBytes</c>（8 KiB）不是一回事</b>：
    /// 那个管**存储**（内联进记录还是进库），这个管**投递**。
    /// 两者数值不同是对的，**别把它们合并**——合并会让「改了存储策略」顺手动到「投递多少」。</para>
    /// </summary>
    public const int MaxResultBytes = 256 * 1024;

    /// <summary>
    /// 工具结果的**保存**上限：一次调用交回的字节超过它，就是**真的**丢数据。
    ///
    /// <para>⚠️ 用户 2026-10-17 裁定：结果**全量保存**、投递时硬截断。
    /// ⇒ 工具侧只剩这一个安全阀——防的是「一次调用把盘 / 内存撑爆」，
    /// 不是「上下文放不放得下」（那是 <see cref="MaxResultBytes"/> 的事）。</para>
    ///
    /// <para>⚠️ **占位值**。⚠️ 盘上的**总量**仍然无界：本数只挡单次调用。
    /// 总量策略属于核心状态管理，单独解决（`04` §8 的库清理至今没有落点）。</para>
    /// </summary>
    public const int MaxToolOutputBytes = 4 * 1024 * 1024;

    /// <summary>
    /// 一次工具结果**投递**给模型时，能用多少字节。
    ///
    /// <para>⚠️ <b>`fetch` 是唯一例外，而且这不违反「一处判」</b>：`fetch` 的结果是**模型点名**
    /// 要的一段窗口，它本身已经被窗口上限约束过；若再按普通结果的预算砍一次，
    /// 「取回」就等于取回了正好放不下的东西——**功能自己抵消自己**。
    /// ⇒ 判据按**工具名**分，两个数都住在这里。</para>
    /// </summary>
    public static int DeliveryBudgetOf(string? toolName) =>
        string.Equals(toolName, "fetch", StringComparison.Ordinal) ? MaxToolOutputBytes : MaxResultBytes;

    /// <summary>
    /// `ls` 一次**最多列多少条**。
    ///
    /// <para>⚠️ **占位值**。`01` §12.5 早就裁过「**展开枚举**（给头和清扫看的清单）**可截断**」，
    /// 而 `ls` 的输出正是一个展开枚举 ⇒ 它该有上限。
    /// ⚠️ 一个 5 万条目的目录**不需要任何大文件**就能把上下文撑爆——`ls` 与 `read` 是**同一个病**。</para>
    /// </summary>
    public const int MaxDirectoryEntries = 1000;

    /// <summary>
    /// `ask` 一次**最多问几个问题**（`01` §3.8）。
    ///
    /// <para>⚠️ **占位值**。多问是**一次询问一个信封**，所以没有协议层的上限兜着——
    /// 一个模型可以在一张卡上塞 500 个问题，而那是**用户**要挨个填的。
    /// ⇒ 这里必须有个数，理由同 <see cref="MaxDirectoryEntries"/>：
    /// 撑爆的是**人的耐心**，不是上下文。</para>
    /// </summary>
    public const int MaxAskItems = 8;

    /// <summary>
    /// `update` 一次**最多动多大的文件**（`01` §9.3）。
    ///
    /// <para>⚠️ **占位值**，理由同上：§9.3 只裁定了「必须有所限制」，没说多少。</para>
    ///
    /// <para>⚠️ <b>它与 <see cref="MaxResultBytes"/> 不是同一个上限，别合并</b>：
    /// 那个管「一次结果**进上下文**多少字节」（读出来给模型看），
    /// 这个管「一次**写**动多少字节」（改盘上的东西）。
    /// `update` 把**整个文件**读进内存做匹配，所以这里防的其实是**内存 + 一次全量重写**，
    /// 而 <see cref="MaxResultBytes"/> 防的是上下文。两者数值相同纯属巧合——
    /// 将来调其中一个时，**没有理由**跟着调另一个。</para>
    ///
    /// <para>⚠️ 超限是**拒绝**，不是「只改一部分」：静默截断会让模型以为改动生效了
    /// （同 <see cref="MaxDirectoryEntries"/> 那条「截断必须明说」的判据，
    /// 而这里连「明说」都做不到——写一半的文件是坏的）。</para>
    /// </summary>
    public const int MaxUpdateBytes = 256 * 1024;
}
